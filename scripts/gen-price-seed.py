# Generates src/data/propPricesSeed.ts from the Prop Firm Scouting bot's ranked scan CSV.
# Only real values from the CSV are used; rows whose all-in can't be reproduced exactly are reported.
import csv, re, json, sys
SRC = '/workspace/propfirms/scan_2026-10-18.csv'
CHECKED = '2026-10-18'
num = lambda s: float(re.search(r'\$([\d,]+(?:\.\d+)?)', s).group(1).replace(',', '')) if re.search(r'\$[\d,]', s or '') else None
out, bad = [], []
for r in csv.DictReader(open(SRC)):
    size = int(r['size'].rstrip('K')) * 1000
    lp = num(r['list_price']); promo = num(r['promo_price']) if r['promo_price'] != 'n/a' else None
    monthly = '/mo' in r['list_price']
    act_s = r['activation_fee']; act = num(act_s) if act_s.strip().startswith('$') else 0.0
    if 'payout' in act_s: act = 0.0  # deducted from first payout, not paid upfront
    if 'monthly' in r['recurring_fees'] and '/mo' in act_s: act = num(act_s)
    pct = 0.0; fee = lp
    m = re.search(r'(\d+)% off', r['promo_price'])
    if promo is not None:
        if m and abs(lp * (1 - int(m.group(1)) / 100) - promo) < 0.01: pct = int(m.group(1))
        else: fee = promo  # built-in/site price: store the discounted fee directly
    mc = re.match(r'\s*([A-Z0-9]{3,})\b', r['promo_code'])
    code = mc.group(1) if promo is not None and mc else ''  # short code; full promo text kept in notes
    allin = round(fee * (1 - pct / 100) + act, 2)
    if abs(allin - float(r['all_in'])) > 0.011: bad.append((r['firm'], size, allin, r['all_in'])); continue
    notes = f"Rank #{r['rank']} in scan. Price: {r['list_price']} → {r['promo_price']}. Promo: {r['promo_code']} ({r['promo_expiry']}). Activation: {act_s}. Recurring: {r['recurring_fees']}. Rules: {r['rules_note']}"
    out.append(dict(id=f"seed-{size//1000}k-{r['rank']}", firm=r['firm'], size=size, evalFee=fee, billing='monthly' if monthly else 'one-time',
        activationFee=act, otherFees=0, promoCode=code, discountPct=pct, notes=notes, url=r['pricing_url'], lastChecked=CHECKED,
        source=f"Prop Firm Scouting bot scan {CHECKED} (scan_2026-10-18.csv) — {r['verification_source']}"))
open('src/data/propPricesSeed.ts', 'w').write(
  "// AUTO-GENERATED by scripts/gen-price-seed.py from /workspace/propfirms/scan_2026-10-18.csv — real prices, do not hand-edit.\n"
  "import type { PriceEntry } from '../lib/propPrices'\n\nexport const SEED_PRICES: PriceEntry[] = " + json.dumps(out, indent=1, ensure_ascii=False) + "\n")
print(len(out), 'rows; skipped', bad)
